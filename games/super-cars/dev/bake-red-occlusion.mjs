// Bake local geometric occlusion into the red paint vertices.
// Runtime only multiplies vertex colours; no extra render pass is required.
import * as THREE from 'three';
import {buildRedRacer} from '../carModels/redRacer.js';
import {writeFileSync} from 'node:fs';
import {redGeometrySignature} from '../carModels/redOcclusion.js';
const geometries=buildRedRacer({occlusion:false});
const material=new THREE.MeshBasicMaterial({side:THREE.DoubleSide});
const obstacles=['paint','carbon'].map(k=>{const mesh=new THREE.Mesh(geometries[k],material);mesh.geometry.computeBoundingBox();mesh.updateMatrixWorld();return mesh;});
const g=geometries.paint,p=g.attributes.position,n=g.attributes.normal;
const factors=[],groups=new Map(),ray=new THREE.Raycaster();ray.near=.006;ray.far=.28;
const origin=new THREE.Vector3(),normal=new THREE.Vector3(),u=new THREE.Vector3(),v=new THREE.Vector3(),direction=new THREE.Vector3(),center=new THREE.Vector3(),sample=new THREE.Vector3();
for(let i=0;i<p.count;i++){
 origin.fromBufferAttribute(p,i);normal.fromBufferAttribute(n,i).normalize();
 center.set(0,0,0);const triangle=Math.floor(i/3)*3;for(let j=0;j<3;j++)center.add(sample.fromBufferAttribute(p,triangle+j));center.multiplyScalar(1/3);
 origin.lerp(center,.12).addScaledVector(normal,.008);
 u.crossVectors(normal,Math.abs(normal.y)<.9?new THREE.Vector3(0,1,0):new THREE.Vector3(1,0,0)).normalize();v.crossVectors(normal,u).normalize();
 let occlusion=0;
 for(let j=0;j<32;j++){
  const r=Math.sqrt((j+.5)/32),theta=j*2.399963229728653;
  direction.copy(u).multiplyScalar(r*Math.cos(theta)).addScaledVector(v,r*Math.sin(theta)).addScaledVector(normal,Math.sqrt(1-r*r));
  ray.set(origin,direction);const hits=ray.intersectObjects(obstacles,false);
  if(hits.length)occlusion+=Math.exp(-hits[0].distance/.16);
 }
 factors.push(1-.65*occlusion/32);
 const key=[p.getX(i),p.getY(i),Math.abs(p.getZ(i)),n.getX(i),n.getY(i),Math.abs(n.getZ(i))].map(x=>x.toFixed(4)).join(',');
 if(!groups.has(key))groups.set(key,[]);groups.get(key).push(i);
}
for(const list of groups.values()){const f=list.reduce((s,i)=>s+factors[i],0)/list.length;for(const i of list)factors[i]=+f.toFixed(4);}
writeFileSync(new URL('../carModels/redOcclusionData.js',import.meta.url),'// Generated by dev/bake-red-occlusion.mjs.\nexport const redOcclusion = '+JSON.stringify({signature:redGeometrySignature(g),factors})+';\n');
console.log({vertices:p.count,min:Math.min(...factors),average:factors.reduce((s,x)=>s+x,0)/factors.length});
